#!/usr/bin/env node
// Builds the ground-truth manifest and inventory from ground-truth/labels.json.
//
//   node evaluation/tools/build-ground-truth.mjs          write findings.json + inventory.md
//   node evaluation/tools/build-ground-truth.mjs --check  exit 1 if either file is stale

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, relative } from 'node:path';
import {
    buildManifest,
    formatRange,
    GT_MANIFEST_PATH,
    INVENTORY_PATH,
    loadGroundTruth,
    REPO_DIR,
    RULE_IDS,
    RULES,
    serializeManifest,
    TIERS,
} from './lib.mjs';

const check = process.argv.includes('--check');

function mdCell(text) {
    return String(text).replace(/\|/g, '\\|');
}

function buildInventory({ labels, spans }) {
    const out = [];
    out.push('# Ground-truth inventory', '');
    out.push(
        'Generated by `tools/build-ground-truth.mjs` from `labels.json`. Do not edit by hand; edit the',
        'labels and re-run the script. Line links point into `../trailmark/`.',
        ''
    );

    out.push('## Summary', '');
    out.push('| Rule | Category | Direct | Boundary | Positives | Hard negatives | Optional |');
    out.push('| --- | --- | ---: | ---: | ---: | ---: | ---: |');
    const totals = { direct: 0, boundary: 0, positives: 0, negatives: 0, optional: 0 };
    for (const rule of RULE_IDS) {
        const pos = spans.flatMap(s => s.positives.filter(l => l.rule === rule));
        const byTier = Object.fromEntries(TIERS.map(t => [t, pos.filter(l => l.tier === t).length]));
        const neg = spans.flatMap(s => s.negatives.filter(l => l.rule === rule)).length;
        const opt = spans.flatMap(s => s.optional.filter(l => l.rule === rule)).length;
        totals.direct += byTier.direct;
        totals.boundary += byTier.boundary;
        totals.positives += pos.length;
        totals.negatives += neg;
        totals.optional += opt;
        out.push(
            `| ${rule} | \`${RULES[rule]}\` | ${byTier.direct} | ${byTier.boundary} | ${pos.length} | ${neg} | ${opt} |`
        );
    }
    out.push(
        `| **Total** | ${spans.length} spans | ${totals.direct} | ${totals.boundary} | ${totals.positives} | ` +
            `${totals.negatives} | ${totals.optional} |`,
        ''
    );

    out.push('## Labels by file', '');
    out.push(
        '`positive` = must be found (a ground-truth finding). `negative` = hard negative: a near miss that',
        'must not be flagged for that rule. `optional` = either answer is defensible; predictions there are',
        'ignored.',
        ''
    );
    for (const [file, meta] of Object.entries(labels.files)) {
        const fileSpans = spans.filter(s => s.file === file);
        out.push(`### \`${file}\` (${meta.language})`, '');
        out.push('| Span | Lines | Rule | Label | Tier | What it probes |');
        out.push('| --- | --- | --- | --- | --- | --- |');
        for (const span of fileSpans) {
            const link = `[${formatRange(span.range)}](../trailmark/${file}#L${span.range.start}-L${span.range.end})`;
            const rows = [
                ...span.positives.map(l => [l.rule, 'positive', l.tier, l.probe]),
                ...span.negatives.map(l => [l.rule, 'negative', l.tier, l.probe]),
                ...span.optional.map(l => [l.rule, 'optional', '', l.why]),
            ];
            for (const [rule, kind, tier, text] of rows) {
                out.push(`| ${span.id} | ${link} | ${rule} | ${kind} | ${tier} | ${mdCell(text)} |`);
            }
        }
        out.push('');
    }
    return out.join('\n');
}

/**
 * If the extension has been compiled, recompute every fingerprint with its own
 * implementation so a drift in the mirrored normalization cannot go unnoticed.
 */
function crossCheckFingerprints(manifest) {
    const compiled = join(REPO_DIR, 'out', 'findings', 'fingerprint.js');
    if (!existsSync(compiled)) {
        return 'skipped (run `npm run compile` in the repo root to enable)';
    }
    const { computeFingerprint } = createRequire(import.meta.url)(compiled);
    let count = 0;
    for (const [file, entry] of Object.entries(manifest.files)) {
        for (const finding of entry.findings) {
            const expected = computeFingerprint(finding.category, finding.excerpt);
            if (expected !== finding.fingerprint) {
                throw new Error(
                    `fingerprint mismatch for ${file}:${formatRange(finding.lineRange)} ${finding.category}: ` +
                        `ours ${finding.fingerprint}, extension ${expected}`
                );
            }
            count += 1;
        }
    }
    return `${count} fingerprints match ${relative(process.cwd(), compiled) || compiled}`;
}

function main() {
    const gt = loadGroundTruth();
    const manifest = buildManifest(gt);
    const outputs = [
        [GT_MANIFEST_PATH, serializeManifest(manifest)],
        [INVENTORY_PATH, buildInventory(gt) + '\n'],
    ];

    const positives = gt.spans.reduce((n, s) => n + s.positives.length, 0);
    const negatives = gt.spans.reduce((n, s) => n + s.negatives.length, 0);
    const optional = gt.spans.reduce((n, s) => n + s.optional.length, 0);
    console.log(
        `${gt.spans.length} spans in ${Object.keys(gt.labels.files).length} files: ` +
            `${positives} positive, ${negatives} hard-negative, ${optional} optional labels`
    );
    console.log(`fingerprint cross-check: ${crossCheckFingerprints(manifest)}`);

    if (check) {
        const stale = outputs.filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text);
        for (const [path] of stale) {
            console.error(`stale: ${relative(process.cwd(), path)}`);
        }
        if (stale.length) {
            console.error('run `node evaluation/tools/build-ground-truth.mjs` to regenerate');
            process.exit(1);
        }
        console.log('ground truth is up to date');
        return;
    }

    for (const [path, text] of outputs) {
        writeFileSync(path, text);
        console.log(`wrote ${relative(process.cwd(), path)}`);
    }
}

try {
    main();
} catch (error) {
    console.error(`error: ${error.message}`);
    process.exit(1);
}
